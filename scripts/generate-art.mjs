#!/usr/bin/env node
/**
 * Generates every bundled artwork (src/content/artworks/<album>/<id>.json) and the content
 * manifest (src/content/index.ts) from the definitions in scripts/art/.
 *
 *   node scripts/generate-art.mjs                    # write all artworks + manifest
 *   node scripts/generate-art.mjs --only fox,owl     # only these ids (manifest untouched)
 *   node scripts/generate-art.mjs --preview <dir>    # also write PNG previews + contact-sheet.png
 *
 * All artworks are original FingerPaint creations (see docs/content-credits.md). Files found
 * under artworks/ that are not generated here (e.g. imported with png-to-artwork.mjs) are kept
 * and appended to the manifest.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { ANIMALS } from './art/animals.mjs';
import { DEEP_OCEAN } from './art/deep-ocean.mjs';
import { fromAscii } from './art/engine.mjs';
import { GARDEN } from './art/garden.mjs';
import { KITCHEN } from './art/kitchen.mjs';
import { OCEAN } from './art/ocean.mjs';
import { writeContactSheet, writePreview } from './art/render.mjs';
import { SPACE } from './art/space.mjs';
import { STARTER } from './art/starter.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const CONTENT = join(ROOT, 'src/content');
const ARTWORKS = join(CONTENT, 'artworks');

const args = process.argv.slice(2);
const argValue = (name) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : undefined;
};
const only = argValue('--only')?.split(',');
const previewDir = argValue('--preview');

const albums = JSON.parse(readFileSync(join(CONTENT, 'albums.json'), 'utf8')).albums;
const albumOrder = new Map(albums.map((a) => [a.id, a.order]));

const DEFS = [
  ...STARTER.map((s) => ({ ...s, draw: () => fromAscii(s) })),
  ...GARDEN,
  ...OCEAN,
  ...KITCHEN,
  ...ANIMALS,
  ...SPACE,
  ...DEEP_OCEAN,
];

const accessRank = (a) => (a === 'free' ? 0 : a === 'pro' ? 1 : 2);
/** Catalog order: album, then free → pro → pack, then easy → hard, then size. */
function catalogCompare(a, b) {
  return (
    (albumOrder.get(a.album) ?? 99) - (albumOrder.get(b.album) ?? 99) ||
    accessRank(a.access) - accessRank(b.access) ||
    a.difficulty - b.difficulty ||
    a.w * a.h - b.w * b.h ||
    a.id.localeCompare(b.id)
  );
}

const ids = new Set();
const sources = [];
for (const def of DEFS) {
  if (ids.has(def.id)) throw new Error(`duplicate id ${def.id}`);
  ids.add(def.id);
  if (only && !only.includes(def.id)) continue;
  const art = def.draw();
  const src = art.toSource(def, def.colors);
  const file = join(ARTWORKS, src.album, `${src.id}.json`);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, `${JSON.stringify(src, null, 2)}\n`);
  sources.push(src);
  const cells = src.rows.join('').length;
  console.log(`wrote ${src.album}/${src.id} (${src.w}×${src.h}, ${src.palette.length} colors, ${cells} rle chars)`);
}

const camel = (id) => id.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

if (!only) {
  // Every artwork file on disk, generated or not.
  const onDisk = [];
  for (const album of readdirSync(ARTWORKS)) {
    for (const f of readdirSync(join(ARTWORKS, album))) {
      if (f.endsWith('.json')) onDisk.push(JSON.parse(readFileSync(join(ARTWORKS, album, f), 'utf8')));
    }
  }
  onDisk.sort(catalogCompare);
  const imports = onDisk
    .map((s) => ({ name: camel(s.id), path: `./artworks/${s.album}/${s.id}.json` }))
    .sort((a, b) => a.path.localeCompare(b.path));
  const manifest = `/**
 * Static content manifest — generated by \`node scripts/generate-art.mjs\` (do not edit by hand).
 * Metro bundles JSON imports, so every artwork must be listed here (content.test.ts fails if
 * a file under artworks/ is missing from this list). The list is in catalog order: album,
 * free → pro → pack, then easy → hard. Data is exposed as \`unknown\` on purpose: the registry
 * validates it before use.
 */
import albums from './albums.json';
${imports.map((i) => `import ${i.name} from '${i.path}';`).join('\n')}

export const albumsData: unknown = albums;

export const artworkData: readonly unknown[] = [
${onDisk.map((s) => `  ${camel(s.id)},`).join('\n')}
];
`;
  writeFileSync(join(CONTENT, 'index.ts'), manifest);
  console.log(`manifest: ${onDisk.length} artworks`);
}

if (previewDir) {
  mkdirSync(previewDir, { recursive: true });
  for (const src of sources) writePreview(src, join(previewDir, `${src.id}.png`));
  const byAlbum = albums
    .slice()
    .sort((a, b) => a.order - b.order)
    .map((a) => sources.filter((s) => s.album === a.id).sort(catalogCompare))
    .filter((r) => r.length > 0);
  if (byAlbum.length) writeContactSheet(byAlbum, join(previewDir, 'contact-sheet.png'));
  console.log(`previews in ${previewDir}${existsSync(previewDir) ? '' : ' (missing?)'}`);
}
